  human-gated (CAPTCHA/2FA), and it is stricter still from a datacenter IP.
  So: export on your own computer, paste here.

  STEP 1 — MAKE A "BURNER" GOOGLE ACCOUNT
  ───────────────────────────────────────
  A burner (= throwaway, disposable) account is a NEW Google account made only
  for this job. Any name, no recovery details you care about, nothing else
  signed in to it, and losing it tomorrow costs you nothing.

  Never use your own Gmail. Two reasons:
    · YouTube flags — and sometimes bans — accounts whose session is used for
      server-side downloading.
    · cookies.txt IS a working login. It sits on this server; anyone who can
      read the file is signed in as that account. It is stored 600 www-data,
      but that is a burner account's job, not your real one's.

  Create it at accounts.google.com, then visit youtube.com once so the account
  has a normal YouTube session.

  STEP 2 — EXPORT THE COOKIE FILE (pick ONE route)
  ────────────────────────────────────────────────
  Route A — private window + extension   [RECOMMENDED]
    1. Install the "Get cookies.txt LOCALLY" browser extension, and allow it
       to run in private windows.
    2. Open a PRIVATE / INCOGNITO window.
    3. Log into youtube.com with the BURNER account.
    4. Open any ordinary video, e.g.
HOWTOEOF
    echo "         ${YTCOOKIE_PROBE_URL:-https://www.youtube.com/watch?v=J6VMJLSNAHk}"
    cat << 'HOWTOEOF'
    5. Click the extension -> Export -> save cookies.txt (Netscape format).
    6. CLOSE the private window WITHOUT logging out.

    Why private: nothing touches that session afterwards, so the cookies you
    exported stay valid. A session you keep browsing with has its cookies
    rotated by the browser and the exported copy dies within hours.

  Route B — let yt-dlp export it (no extension)
    1. Use a NORMAL window — not private. This route reads the browser's
       on-disk cookie database, and private-window cookies are memory-only,
       so they are invisible to it.
    2. Best in a Firefox profile kept only for the burner account, so your
       everyday browsing does not rotate the session away.
    3. Log in as the burner, then CLOSE Firefox (do not log out).
    4. Run:
HOWTOEOF
    echo "         yt-dlp --cookies-from-browser firefox --cookies cookies.txt \\"
    echo "                --skip-download \"${YTCOOKIE_PROBE_URL:-https://www.youtube.com/watch?v=J6VMJLSNAHk}\""
    cat << 'HOWTOEOF'
    Firefox, not Chrome: Chrome's app-bound cookie encryption commonly breaks
    --cookies-from-browser chrome.

  THE ONE RULE THAT DECIDES WHETHER THIS WORKS
  ────────────────────────────────────────────
  Never log the burner out, and do not keep browsing YouTube in that session.
  Logging out invalidates the session on Google's side, which kills the
  exported file too — that is the #1 reason server cookies "work for an hour
  and then die".

  STEP 3 — INSTALL IT HERE
  ────────────────────────
  Open cookies.txt in a text editor, copy all of it, come back to this menu
  and choose 1) Paste cookies.txt content. Paste, then a line with only EOF.
  This script validates it, installs it 600 www-data, sets YTDLP_COOKIES in
  the yt-server .env, installs the keep-alive cron, restarts yt-server and
  runs a probe so you see immediately whether YouTube accepted it.

  (Already have the file on this server? Use 2) Import from a path instead.)

  RENEWING — WHEN AND HOW
  ───────────────────────
  Cookies last weeks, not forever. You do not have to watch for it:
    · a cron probe runs every 6 hours (ytcookie-keepalive.sh). It keeps the
      session rotating, and when Google finally rejects it the probe writes
      "expired" into cookies.status;
    · /health then reports "cookies":"file:expired", and the yt-downloader
      page shows an orange "cookies expired" warning next to the backend line;
    · option 3 here re-runs that probe on demand.
  To renew: repeat STEP 2 with the same burner account (log in again if it was
  signed out) and paste the new file over the old one with option 1.

  TROUBLESHOOTING
  ───────────────
    "file:missing"      YTDLP_COOKIES in .env points at a file that is gone.
    "file:unchecked"    installed, cron has not probed yet — use option 3.
    inconclusive probe  network/YouTube hiccup, or the probe video was
                        removed. The old status is kept on purpose. Override
                        the video with YTCOOKIE_PROBE_URL if needed.
    still bot-checked   confirm office-tools-pot is running and yt-dlp is
                        current (Option 6 -> h), then re-export the cookies.
HOWTOEOF
    echo ""
}

# Runs the keep-alive probe once (as www-data, exactly as cron will) and prints both
# its verdict and what /health now reports.
_cookie_probe() {
    local ka="${YT_SERVER_DIR}/ytcookie-keepalive.sh"
    if [[ -x "$ka" ]]; then
        info "Probing cookies with yt-dlp…"
        # Run as the service user so a rotated cookies.txt keeps www-data ownership.
        if command -v runuser &>/dev/null; then
            runuser -u www-data -- "$ka" 2>&1 | sed 's/^/    /' || true
        else
            su -s /bin/bash www-data -c "$ka" 2>&1 | sed 's/^/    /' || true
        fi
    else
        warn "Keep-alive script not found at $ka — run Option 6 → h to sync yt-server."
    fi
    # PORT is operator-editable in .env — do not assume 9000, or this reports a healthy
    # server as down on any box where it was changed.
    local port health
    port="$(sed -n 's/^[[:space:]]*PORT=//p' "${YT_SERVER_DIR}/.env" 2>/dev/null | tail -n1 | tr -d "\"' ")"
    port="${port:-9000}"
    health="$(curl -s --max-time 5 "http://127.0.0.1:${port}/health" 2>/dev/null || true)"
    if [[ -n "$health" ]]; then
        echo -e "  ${BOLD}/health:${RESET} ${health}"
    else
        warn "yt-server not answering on 127.0.0.1:${port} — check: journalctl -u office-tools-cobalt -n 30"
    fi
}

# ─── DEL: Delete ──────────────────────────────────────────────────────────────
opt_del_delete() {
    show_banner
    section "Delete — Remove Office Tools"

    echo -e "  ${RED}${BOLD}This will PERMANENTLY remove Office Tools from this server.${RESET}"
    echo ""

    # Locate undeploy.sh
    local _undeploy=""
    for _p in \
        "$SCRIPT_DIR/undeploy.sh" \
        "$REPO_DIR/undeploy.sh" \
        "/opt/office-tools/repo/undeploy.sh"; do
        [[ -f "$_p" ]] && _undeploy="$_p" && break
    done

    if [[ -z "$_undeploy" ]]; then
        die "undeploy.sh not found. Copy it next to deploy.sh and retry."
    fi

    info "Will run: $_undeploy"
    echo ""
    bash "$_undeploy"
}

