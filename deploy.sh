        # config is generated from a template with no manual customisations.
        if systemctl is-active --quiet nginx 2>/dev/null && [[ -n "${DOMAIN:-}" ]]; then
            local ssl_cert="/etc/letsencrypt/live/${DOMAIN}/fullchain.pem"
            if [[ -f "$ssl_cert" ]]; then
