    # Prerequisites check
    if ! command -v nginx &>/dev/null; then
        warn "nginx not installed. Run Option 1 first."
        press_enter; return 0
    fi
    if ! command -v certbot &>/dev/null; then
        warn "certbot not installed. Run Option 1 first."
        press_enter; return 0
    fi
