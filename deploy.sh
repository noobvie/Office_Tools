  ──────────────────
  YouTube answers datacenter/VPS IPs with "Sign in to confirm you're not a
  bot". The PO-token provider (office-tools-pot) handles most of that, but on a
  flagged IP YouTube also wants a logged-in session — that is what cookies.txt
