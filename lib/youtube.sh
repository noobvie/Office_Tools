# ─── ffmpeg ───────────────────────────────────────────────────────────────────
# Required by yt-dlp for MP3 conversion and 1080p video muxing.
install_ffmpeg() {
    section "Installing ffmpeg"

    if command -v ffmpeg &>/dev/null; then
        info "ffmpeg already installed: $(ffmpeg -version 2>&1 | head -1 | awk '{print $3}')"
        return 0
    fi

    info "Installing ffmpeg…"
    if [[ "$OS_FAMILY" == "debian" ]]; then
        pkg_install ffmpeg
    else
        # RHEL-family: ffmpeg lives in RPM Fusion (not in default repos).
        # EPEL is already installed by install_base_packages.
        local rhel_ver
        rhel_ver=$(rpm -E %rhel 2>/dev/null || echo 9)
        local rpm_fusion="https://download1.rpmfusion.org/free/el/rpmfusion-free-release-${rhel_ver}.noarch.rpm"
        dnf install -y "$rpm_fusion" 2>/dev/null \
            || warn "RPM Fusion install failed — trying dnf without it"
        dnf install -y ffmpeg 2>/dev/null \
            || warn "ffmpeg unavailable — video processing may be limited"
    fi
    command -v ffmpeg &>/dev/null \
        && success "ffmpeg installed: $(ffmpeg -version 2>&1 | head -1)" \
        || warn "ffmpeg not found — install manually if needed"
}

# ─── yt-dlp + JS runtime + PO-token plugin ────────────────────────────────────
# Required by yt-server for video/audio downloading. The pip work lives in ONE generated
# script, /opt/office-tools/yt-update.sh, which this function runs and the daily cron
# runs again — so a deploy and a nightly update can never install different things.
#
# What that script installs, and why each part is there:
#   yt-dlp[default]   the downloader plus yt-dlp-ejs, the scripts that solve YouTube's
#                     JavaScript challenges. A bare `pip install yt-dlp` has no solver
#                     scripts, and yt-dlp then extracts with formats missing.
#   [deno]            the Deno binary those scripts run in. yt-dlp enables Deno by itself
#                     and finds the pip package without it being on PATH. Deno runs the
#                     player code with no file or network access, which is why it is the
#                     runtime of choice for code YouTube controls.
#   --pre             the nightly channel. YouTube fixes land there first and stable can
#                     trail a breakage by weeks; upstream recommends nightly for YouTube.
#   bgutil-ytdlp-pot-provider
#                     the bot-check bypass yt-dlp sanctions: YouTube requires PO (Proof
#                     of Origin) tokens on most player clients, and this plugin fetches
#                     them from the local token server (see setup_pot_provider).
install_ytdlp() {
    section "Installing yt-dlp + JS runtime + PO-token plugin"

    # yt-dlp needs Python 3.11+. On an older Python pip does not fail: it keeps
    # reinstalling the last release that still supported it, so every update "succeeds"
    # while the downloader falls further behind YouTube.
    if ! python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)' 2>/dev/null; then
        warn "Python $(python3 -V 2>&1 | awk '{print $2}') is older than 3.11 — pip can only install an outdated yt-dlp here"
    fi

    mkdir -p /opt/office-tools
    local updater="/opt/office-tools/yt-update.sh"
    cat > "$updater" << 'UPDEOF'
#!/bin/bash
# Auto-generated by deploy.sh — installs/updates the YouTube download stack.
# Run by deploy.sh and by /etc/cron.daily/yt-dlp-update.
# Silent on success so the daily cron sends no mail; every failure goes to stderr.
# Exit 1 only when yt-dlp itself could not be installed.
export PIP_DISABLE_PIP_VERSION_CHECK=1

# --break-system-packages: Ubuntu 22.04+ / Debian 12+ refuse a system-wide pip install
# without it (PEP 668). An older pip rejects the flag itself, hence the second attempt.
pip_up() {
    pip3 install -q -U "$@" --break-system-packages 2>/dev/null \
        || pip3 install -q -U "$@"
}

# Deno ships as a wheel for common platforms only. Where there is none, install the
# rest anyway: yt-server names its own Node binary as a fallback runtime.
if ! pip_up --pre "yt-dlp[default,deno]"; then
    echo "yt-update: could not install the Deno extra — installing yt-dlp without it" >&2
    pip_up --pre "yt-dlp[default]" \
        || { echo "yt-update: yt-dlp install failed" >&2; exit 1; }
fi

# Its own command: --pre must apply to yt-dlp only. The provider server is checked out
# at the plugin's version tag, and a pre-release plugin has no such tag.
pip_up bgutil-ytdlp-pot-provider \
    || echo "yt-update: PO-token plugin install failed" >&2

# Bring the provider server to the plugin's version (written by setup_pot_provider;
# absent on the first install, which builds the provider right after this script).
if [[ -x /opt/office-tools/pot-update.sh ]]; then
    /opt/office-tools/pot-update.sh \
        || echo "yt-update: PO-token provider update failed" >&2
fi
exit 0
UPDEOF
    chmod 755 "$updater"

    info "Installing/updating yt-dlp (nightly), yt-dlp-ejs, Deno and the PO-token plugin…"
    "$updater" || { warn "yt-dlp install failed — YouTube downloads will not work"; return 0; }

    # Daily: yt-server starts a fresh yt-dlp per request, so a new version is live for
    # the next download with no restart — which is what makes a nightly cadence safe to
    # run against in-flight downloads.
    local cron_file="/etc/cron.daily/yt-dlp-update"
    cat > "$cron_file" << 'CRONEOF'
#!/bin/bash
# Auto-generated by deploy.sh — keeps the YouTube download stack current.
exec /opt/office-tools/yt-update.sh
CRONEOF
    chmod 755 "$cron_file"
    # The updater ran from cron.weekly on installs made before it moved to cron.daily;
    # left in place it would run the old stable-channel command once a week.
    rm -f /etc/cron.weekly/yt-dlp-update
    success "Daily auto-update cron installed (yt-dlp nightly + JS runtime + PO-token plugin + provider)"

    if ! command -v yt-dlp &>/dev/null; then
        warn "yt-dlp not found — run: /opt/office-tools/yt-update.sh"
        return 0
    fi
    success "yt-dlp installed: $(yt-dlp --version)"

    # A missing piece here does not stop yt-dlp from running — it runs and quietly offers
    # fewer formats — so say which piece is absent now, while someone is reading.
    local ejs_ver deno_ver
    ejs_ver=$(pip3 show yt-dlp-ejs 2>/dev/null | awk '/^Version:/{print $2}') || true
    deno_ver=$(pip3 show deno 2>/dev/null | awk '/^Version:/{print $2}') || true
    if [[ -n "$ejs_ver" ]]; then
        info "JS challenge scripts: yt-dlp-ejs ${ejs_ver}"
    else
        warn "yt-dlp-ejs is not installed — YouTube formats will be missing"
    fi
    if [[ -n "$deno_ver" ]]; then
        info "JS runtime: Deno ${deno_ver}"
    else
        warn "Deno is not installed — yt-server falls back to its own Node binary ($(node -v 2>/dev/null || echo 'not found'); yt-dlp needs 22+)"
    fi
}

# git inside the provider checkout, run as its owner. The tree belongs to www-data (the
# service runs from it) and git refuses a repository owned by another user — root
# included — with "detected dubious ownership". Run as root, every fetch after the first
# install would fail and the checkout would stay on the version it was cloned at.
_pot_git() {
    # From /: runuser keeps the caller's directory, and www-data cannot read /root.
    ( cd / && runuser -u www-data -- git -C "$POT_SERVER_DIR" "$@" )
}

# Records which plugin version the provider build under $POT_SERVER_DIR matches.
# pot-update.sh reads it to skip a rebuild, so it is written only after a build that
# was made from that version's tag.
POT_BUILT_STAMP=".ot-built-version"

# ─── PO-token provider server (bgutil) ────────────────────────────────────────
# Runs BotGuard locally and mints PO tokens on demand (port 4416). The pip plugin
# installed by install_ytdlp auto-detects it at http://127.0.0.1:4416 — no yt-dlp
# flags needed. Server checkout is pinned to the installed plugin's version tag
# (plugin and server must match per upstream docs).
setup_pot_provider() {
    section "Setting up PO-token provider (bgutil, port ${POT_PORT})"

    # Node ≥ 20 required by the provider (install_nodejs puts a current LTS in place)
    local node_major
    node_major=$(node -v 2>/dev/null | sed 's/^v//' | cut -d. -f1)
    if [[ -z "$node_major" || "$node_major" -lt 20 ]]; then
        warn "Node.js ≥ 20 required for the PO-token provider (found: $(node -v 2>/dev/null || echo none)) — skipping"
        return 0
    fi

    # Match the server checkout to the installed pip plugin version
    local pot_ver
    pot_ver=$(pip3 show bgutil-ytdlp-pot-provider 2>/dev/null | awk '/^Version:/{print $2}')
    if [[ -z "$pot_ver" ]]; then
        warn "bgutil-ytdlp-pot-provider pip plugin not installed — run install_ytdlp first; skipping"
        return 0
    fi

    if [[ -d "$POT_SERVER_DIR/.git" ]]; then
        info "Updating provider checkout to v${pot_ver}…"
        # A build that failed on an earlier run returned before the chown further down
        # and may have left root-owned files that www-data's git cannot replace.
        chown -R www-data:www-data "$POT_SERVER_DIR" \
            || warn "could not chown $POT_SERVER_DIR — the update below may fail"
        _pot_git fetch --tags -q origin \
            || warn "git fetch failed — building current checkout"
    else
        info "Cloning bgutil-ytdlp-pot-provider…"
        rm -rf "${POT_SERVER_DIR:?}"
        git clone -q https://github.com/Brainicism/bgutil-ytdlp-pot-provider.git "$POT_SERVER_DIR" \
            || { warn "clone failed — PO-token provider not installed (YouTube may serve bot-check 403s)"; return 0; }
        chown -R www-data:www-data "$POT_SERVER_DIR" \
            || warn "could not chown $POT_SERVER_DIR — the checkout below may fail"
    fi
    # A new build is about to replace the old one; the stamp comes back only if it succeeds.
    rm -f "$POT_SERVER_DIR/$POT_BUILT_STAMP"
    local tag_ok=1
    if ! _pot_git -c advice.detachedHead=false checkout -q "$pot_ver" 2>/dev/null; then
        tag_ok=0
        warn "tag ${pot_ver} not found — building default branch instead"
    fi

    info "Building provider (npm ci + tsc)…"
    ( cd "$POT_SERVER_DIR/server" && npm ci --silent && npx tsc ) \
        || { warn "provider build failed — check npm/node output above"; return 0; }
    # No stamp for a default-branch build: the daily updater must keep trying for the tag.
    if [[ "$tag_ok" -eq 1 ]]; then
        printf '%s\n' "$pot_ver" > "$POT_SERVER_DIR/$POT_BUILT_STAMP" \
            || warn "could not write the build stamp — the daily updater will rebuild the provider once"
    fi
    chown -R www-data:www-data "$POT_SERVER_DIR"

    # Standalone updater, run by yt-update.sh (deploy + daily cron): keeps the provider
    # server on the same version as the pip plugin.
    cat > /opt/office-tools/pot-update.sh << POTUPEOF
#!/bin/bash
# Auto-generated by deploy.sh — sync PO-token provider server to the pip plugin version.
set -e
ver=\$(pip3 show bgutil-ytdlp-pot-provider 2>/dev/null | awk '/^Version:/{print \$2}')
[[ -n "\$ver" && -d "$POT_SERVER_DIR/.git" ]] || exit 0
cd "$POT_SERVER_DIR"
# Already built from this version's tag: nothing to do. Without this check the daily
# cron would rebuild the provider and restart it every night.
if [[ "\$(cat $POT_BUILT_STAMP 2>/dev/null)" == "\$ver" ]]; then exit 0; fi
# git as the tree's owner — it refuses a repository owned by another user, root included.
g() { runuser -u www-data -- git "\$@"; }
g fetch --tags -q origin || exit 0
g -c advice.detachedHead=false checkout -q "\$ver" || exit 0
rm -f $POT_BUILT_STAMP
# Explicit exit: set -e does not fire for a command that fails inside an && list, and a
# failed build must not be stamped as done or restarted into.
( cd server && npm ci --silent && npx tsc ) || exit 1
printf '%s\n' "\$ver" > $POT_BUILT_STAMP
chown -R www-data:www-data "$POT_SERVER_DIR"
systemctl restart office-tools-pot 2>/dev/null || true
POTUPEOF
    chmod +x /opt/office-tools/pot-update.sh

    # Systemd service — the provider has no bind-address option (listens on all
    # interfaces), so block external access at the firewall when ufw is active.
    cat > /etc/systemd/system/office-tools-pot.service << POTEOF
[Unit]
Description=Office Tools — bgutil PO-token provider (YouTube bot-check bypass)
After=network.target

[Service]
Type=simple
User=www-data
Group=www-data
WorkingDirectory=${POT_SERVER_DIR}/server
ExecStart=/usr/bin/node build/main.js --port ${POT_PORT}
Environment=TZ=UTC
Restart=on-failure
RestartSec=5s
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
POTEOF

    if command -v ufw &>/dev/null && ufw status 2>/dev/null | grep -q "Status: active"; then
        ufw deny "${POT_PORT}/tcp" >/dev/null 2>&1 || true
        info "ufw: external access to :${POT_PORT} denied (provider is localhost-only by policy)"
    fi

    svc_write_hardening office-tools-pot
    systemctl daemon-reload
    systemctl enable office-tools-pot >/dev/null 2>&1
    systemctl restart office-tools-pot
    svc_verify_hardening office-tools-pot

    sleep 2
    if curl -s -m 5 "http://127.0.0.1:${POT_PORT}/ping" | grep -q version; then
        success "PO-token provider running on http://127.0.0.1:${POT_PORT}/ (v${pot_ver})"
    else
        warn "PO-token provider not responding — check: journalctl -u office-tools-pot -n 30"
    fi
}

# ─── yt-server (YouTube download backend) ─────────────────────────────────────
# Keys every yt-server .env must have; added only when absent, so an operator value wins.
# The unit loads this file (EnvironmentFile=); server.js reads HOST and binds 0.0.0.0
# without it. Loopback because nginx (proxy_pass http://127.0.0.1:9000) is the only
# client and the server trusts forwarded addresses only from a loopback peer.
_yt_env_defaults() {
    env_ensure "$YT_SERVER_DIR/.env" HOST 127.0.0.1 \
        || warn "Could not add HOST to $YT_SERVER_DIR/.env — yt-server keeps listening on all interfaces"
    env_ensure "$YT_SERVER_DIR/.env" NODE_ENV production \
        || warn "Could not add NODE_ENV to $YT_SERVER_DIR/.env"
    return 0
}

setup_yt_server() {
    section "Setting up yt-server (YouTube download backend)"

    mkdir -p "$YT_SERVER_DIR"
    rsync -a "$REPO_DIR/yt-server/" "$YT_SERVER_DIR/"

    cd "$YT_SERVER_DIR" && npm_install_prod && cd /

    # Ensure .env — never rewrite it. setup_yt_server runs on EVERY Option 1, so a
    # truncating write here would wipe operator keys (YTDLP_COOKIES most of all, whose
    # loss looks exactly like YouTube blocking the server again, with nothing logged).
    env_ensure "$YT_SERVER_DIR/.env" PORT 9000
    _yt_env_defaults
    chmod 600 "$YT_SERVER_DIR/.env"
    chmod +x "$YT_SERVER_DIR/ytcookie-keepalive.sh" 2>/dev/null || true
    chown -R www-data:www-data "$YT_SERVER_DIR"

    setup_cookie_keepalive

    # Create systemd service
    cat > /etc/systemd/system/office-tools-cobalt.service << COBEOF
[Unit]
Description=Office Tools — yt-server YouTube Download Server
After=network.target

[Service]
Type=simple
User=www-data
Group=www-data
WorkingDirectory=${YT_SERVER_DIR}
ExecStart=/usr/bin/node server.js
Environment=TZ=UTC
EnvironmentFile=-${YT_SERVER_DIR}/.env
Restart=on-failure
RestartSec=5s
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
COBEOF
    svc_write_hardening office-tools-cobalt

    systemctl daemon-reload
    systemctl enable office-tools-cobalt
    systemctl restart office-tools-cobalt
    svc_verify_hardening office-tools-cobalt

    sleep 3
    if systemctl is-active --quiet office-tools-cobalt; then
        success "yt-server running on http://127.0.0.1:9000/"
    else
        warn "yt-server failed to start — check: journalctl -u office-tools-cobalt -n 30"
    fi
}

# ─── Cookie keep-alive (cron) ─────────────────────────────────────────────────
# yt-server's /health reads <cookie-dir>/cookies.status to report "file:ok" vs
# "file:expired"; nothing writes that file except this cron. Without it /health is
# stuck on "file:unchecked" and cookie expiry is invisible until downloads break.
# The probe also makes yt-dlp rotate the cookie file, which is what keeps a parked
# session alive between real downloads.
setup_cookie_keepalive() {
    local cron_file="/etc/cron.d/office-tools-ytcookie"
    local log_file="${LOG_DIR}/ytcookie-keepalive.log"

    mkdir -p "$LOG_DIR"
    touch "$log_file"
    chown www-data:www-data "$log_file" 2>/dev/null || true

    # Runs as www-data — the user yt-server runs as, so the rotated cookie file keeps
    # its owner. A root-run probe would leave a root-owned cookies.txt behind and the
    # service could no longer write to it.
    cat > "$cron_file" << CRONEOF
# Auto-generated by deploy.sh — YouTube cookie keep-alive + expiry reporting.
# No-op when YTDLP_COOKIES is unset in ${YT_SERVER_DIR}/.env.
SHELL=/bin/bash
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
17 */6 * * * www-data ${YT_SERVER_DIR}/ytcookie-keepalive.sh >> ${log_file} 2>&1
CRONEOF
    chmod 644 "$cron_file"

    cat > /etc/logrotate.d/office-tools-ytcookie << 'LOGROTEOF'
/var/log/office-tools/ytcookie-keepalive.log {
    monthly
    rotate 3
    missingok
    notifempty
    compress
    copytruncate
}
LOGROTEOF

    success "Cookie keep-alive cron installed (every 6h, logs → ${log_file})"
}

sync_yt_server() {
    [[ -d "$YT_SERVER_DIR" ]] || return 0
    section "Syncing yt-server (YouTube download backend)"
    # --exclude='.env' keeps operator settings (YTDLP_COOKIES) across syncs.
    rsync -a --exclude='.env' --exclude='cookies.txt' --exclude='cookies.status' \
        "$REPO_DIR/yt-server/" "$YT_SERVER_DIR/"
    cd "$YT_SERVER_DIR" && npm_install_prod && cd /
    _yt_env_defaults
    chmod 600 "$YT_SERVER_DIR/.env" 2>/dev/null || true
    chmod +x "$YT_SERVER_DIR/ytcookie-keepalive.sh" 2>/dev/null || true
    chown -R www-data:www-data "$YT_SERVER_DIR"
    setup_cookie_keepalive
    svc_write_hardening office-tools-cobalt
    systemctl restart office-tools-cobalt 2>/dev/null || true
    svc_verify_hardening office-tools-cobalt
    success "yt-server synced and restarted"
}


